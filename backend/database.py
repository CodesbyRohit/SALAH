"""
SALAH — database location and first-run initialisation.

Single source of truth for WHERE the SQLite database (and the local interaction
log) live, and for creating the synthetic demo database when it is missing.

Location (first match wins):
  1. SALAH_DB_PATH            explicit database file
  2. SALAH_DATA_DIR           explicit data directory
  3. <tempdir>/salah          on Vercel / AWS Lambda, or when the project's
                              data/ directory is not writable. The deployment
                              bundle is read-only and only /tmp is writable.
  4. <project>/data           local development (unchanged behaviour)

Initialisation (ensure_database):
  * Missing file, zero-byte file, or a SQLite file with no tables → the dataset
    is generated by dataset.populate() into a private temp file in the same
    directory, validated, then moved into place with os.replace (atomic).
    Concurrent initialisers — threads or processes — each build an identical
    deterministic copy; readers never observe a partially written database.
  * A file that HAS tables but fails validation is never overwritten: a
    DatabaseUnavailable error is raised instead. Nothing destructive happens on
    the request path.

/tmp is ephemeral and may be per-instance: on serverless each cold instance can
initialise its own copy of the (deterministic) synthetic dataset. Persistent or
shared merchant data would need a managed database.
"""
from __future__ import annotations

import os
import sqlite3
import tempfile
import threading
from pathlib import Path

import dataset

PROJECT_DATA_DIR = Path(__file__).resolve().parent.parent / "data"
DB_FILENAME = "merchant.db"

REQUIRED_COLUMNS = {
    "transactions": {"id", "customer_id", "amount", "items", "ts"},
    "customers": {"id", "first_visit", "spend_history"},
    "meta": {"key", "value"},
}


class DatabaseUnavailable(RuntimeError):
    """The merchant database could not be found, created or validated."""


_lock = threading.Lock()
_ready: set[str] = set()


# ---------------------------------------------------------------------------
# Location
# ---------------------------------------------------------------------------

def is_serverless() -> bool:
    return bool(os.getenv("VERCEL") or os.getenv("AWS_LAMBDA_FUNCTION_NAME"))


def _writable(directory: Path) -> bool:
    probe = directory if directory.exists() else directory.parent
    return probe.exists() and os.access(probe, os.W_OK)


def data_dir() -> Path:
    override = os.getenv("SALAH_DATA_DIR")
    if override:
        return Path(override)
    if is_serverless() or not _writable(PROJECT_DATA_DIR):
        return Path(tempfile.gettempdir()) / "salah"
    return PROJECT_DATA_DIR


def db_path() -> Path:
    override = os.getenv("SALAH_DB_PATH")
    return Path(override) if override else data_dir() / DB_FILENAME


def location_kind(path: Path | None = None) -> str:
    """'custom' | 'ephemeral' | 'project' — safe to show; no absolute paths."""
    path = path or db_path()
    if os.getenv("SALAH_DB_PATH") or os.getenv("SALAH_DATA_DIR"):
        return "custom"
    try:
        path.resolve().relative_to(PROJECT_DATA_DIR.resolve())
        return "project"
    except ValueError:
        return "ephemeral"


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

def _read_only(path: Path) -> sqlite3.Connection:
    """Open without ever creating the file (plain connect() would)."""
    return sqlite3.connect(f"{Path(path).resolve().as_uri()}?mode=ro", uri=True)


def _table_names(path: Path) -> set[str] | None:
    """Table names, or None when there is no usable database at `path`."""
    if not path.exists() or path.stat().st_size == 0:
        return None
    conn = _read_only(path)
    try:
        return {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    finally:
        conn.close()


def validate(path: Path) -> list[str]:
    """Return a list of problems; empty means the database is usable."""
    try:
        tables = _table_names(path)
    except sqlite3.Error as exc:
        return [f"not a readable SQLite database ({exc})"]
    if tables is None:
        return ["database file is missing or empty"]
    problems: list[str] = []
    conn = _read_only(path)
    try:
        for table, columns in REQUIRED_COLUMNS.items():
            if table not in tables:
                problems.append(f"missing table {table}")
                continue
            present = {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
            missing = columns - present
            if missing:
                problems.append(f"{table} missing columns {sorted(missing)}")
        if problems:
            return problems
        row = conn.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone()
        if not row or row[0] != dataset.SCHEMA_VERSION:
            problems.append(f"schema_version {row[0] if row else None!r} != {dataset.SCHEMA_VERSION!r}")
        count, max_ts = conn.execute("SELECT COUNT(*), MAX(ts) FROM transactions").fetchone()
        if not count or max_ts is None:
            problems.append("transactions table is empty")
    except sqlite3.Error as exc:
        problems.append(f"query failed ({exc})")
    finally:
        conn.close()
    return problems


# ---------------------------------------------------------------------------
# Initialisation
# ---------------------------------------------------------------------------

def _build_into_place(path: Path, replace_existing: bool) -> dict:
    """Generate into a private temp file, validate it, then atomically move it
    to `path`. Returns the dataset summary."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    try:
        tmp.unlink(missing_ok=True)
        conn = sqlite3.connect(tmp)
        try:
            summary = dataset.populate(conn)
            conn.commit()
        finally:
            conn.close()
        problems = validate(tmp)
        if problems:
            raise DatabaseUnavailable(f"generated database failed validation: {problems}")
        if not replace_existing and path.exists() and not validate(path):
            return summary  # another initialiser finished first
        try:
            os.replace(tmp, path)
        except OSError:
            # e.g. Windows refuses to replace a file another process has open.
            # Acceptable only if a valid database is already in place.
            if validate(path):
                raise
        return summary
    finally:
        tmp.unlink(missing_ok=True)


def ensure_database(path: Path | None = None) -> Path:
    """Return a validated database path, creating the synthetic dataset on
    first use. Idempotent and safe under concurrent first requests."""
    path = Path(path) if path else db_path()
    key = str(path)
    if key in _ready and path.exists():
        return path
    with _lock:
        if key in _ready and path.exists():
            return path
        _ready.discard(key)
        try:
            tables = _table_names(path)
        except sqlite3.Error as exc:
            raise DatabaseUnavailable(f"{path.name} exists but is not readable SQLite ({exc}); refusing to overwrite") from exc
        except OSError as exc:
            raise DatabaseUnavailable(f"cannot access {path.name} ({exc})") from exc
        if not tables:  # missing, zero-byte, or no tables: nothing to lose
            try:
                _build_into_place(path, replace_existing=False)
            except DatabaseUnavailable:
                raise
            except (OSError, sqlite3.Error) as exc:
                raise DatabaseUnavailable(f"could not create {path.name} in its data directory ({exc})") from exc
        problems = validate(path)
        if problems:
            raise DatabaseUnavailable(f"{path.name} failed validation: {'; '.join(problems)}")
        _ready.add(key)
    return path


def rebuild_database(path: Path | None = None) -> dict:
    """Explicitly regenerate the dataset, replacing any existing file.
    Destructive — used only by the data/seed.py command, never per request."""
    path = Path(path) if path else db_path()
    with _lock:
        _ready.discard(str(path))
        summary = _build_into_place(path, replace_existing=True)
        _ready.add(str(path))
    return summary


def connect() -> sqlite3.Connection:
    """Read-only connection to the (initialised) merchant database."""
    path = ensure_database()
    try:
        conn = _read_only(path)
    except sqlite3.OperationalError:
        # The file vanished after initialisation (e.g. /tmp was cleared): retry once.
        _ready.discard(str(path))
        conn = _read_only(ensure_database())
    conn.row_factory = sqlite3.Row
    return conn


def status() -> dict:
    """Initialise if needed and report the outcome (for /api/health)."""
    path = db_path()
    try:
        ensure_database(path)
        return {"ready": True, "location": location_kind(path), "error": None}
    except DatabaseUnavailable as exc:
        return {"ready": False, "location": location_kind(path), "error": str(exc)}
