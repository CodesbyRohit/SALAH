export const DICTIONARIES = { en, hi, es, fr };

function lookup(dict, key) {
  return key.split(".").reduce((node, part) => (node == null ? undefined : node[part]), dict);
}

export function translate(lang, key, vars) {
  let value = lookup(DICTIONARIES[lang] || en, key);
  if (value === undefined) value = lookup(en, key);
  if (value === undefined) return key;
  if (typeof value !== "string" || !vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

export function flattenKeys(obj, prefix = "") {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === "object" && !Array.isArray(v) ? flattenKeys(v, `${prefix}${k}.`) : [`${prefix}${k}`],
  );
}
